local VAMain = require("VAMain")

local exports = exports or {}
local SeekModeScript = SeekModeScript or {}
SeekModeScript.__index = SeekModeScript


function SeekModeScript.new (construct, ...)
    local self = setmetatable({}, SeekModeScript)

    self.curTime = 0
    self.duration = 3

    self.node = {}
    self.data = {}
    self.main = VAMain.new()

    return self
end

function SeekModeScript:onStart (comp)
    self:_adapt_onStart(comp)
    self.rootDir = comp.entity.scene.assetMgr.rootDir
    --
    self.data.w0 = Amaz.BuiltinObject.getInputTextureWidth()
    self.data.h0 = Amaz.BuiltinObject.getInputTextureHeight()
    self.main:create(self.node, self.data, self.data.w0, self.data.h0, comp.entity.scene)
    self.main:layout(self.node, self.data, self.data.w0, self.data.h0)
    self.main:update(self.node, self.data, self.data.w0, self.data.h0, 1, 0, 0)
    --
end

function SeekModeScript:seek (time)
    self:_adapt_seek(time)
    --
    local w = Amaz.BuiltinObject.getInputTextureWidth()
    local h = Amaz.BuiltinObject.getInputTextureHeight()
    if w ~= self.data.w0 or h ~= self.data.h0 then
        self.data.w0 = w
        self.data.h0 = h
        self.main:layout(self.node, self.data, self.data.w0, self.data.h0)
    end
    self.main:update(self.node, self.data, self.data.w0, self.data.h0, self.duration, time, time / self.duration)
    --
end

