function Main:layout (node, data, w, h)
    node.rt0.width = w
    node.rt0.height = h
    node.rt1.width = w
    node.rt1.height = h

    local screenSize = Amaz.Vector2f(w, h)
    node.motion:setVec2("u_screen_size", screenSize)

    node.blur1r:setVec2("u_screen_size", screenSize)
    node.blur2r:setVec2("u_screen_size", screenSize)
	node.blur3r:setVec2("u_screen_size", screenSize)
	node.blur4r:setVec2("u_screen_size", screenSize)

	node.blur1c:setVec2("u_screen_size", screenSize)
	node.blur2c:setVec2("u_screen_size", screenSize)
	node.blur3c:setVec2("u_screen_size", screenSize)
	node.blur4c:setVec2("u_screen_size", screenSize)

    local center = Amaz.Vector2f(w * 0.5, h * 0.5)
    node.blur1r:setVec2("u_center", center)
    node.blur2r:setVec2("u_center", center)
	node.blur3r:setVec2("u_center", center)
	node.blur4r:setVec2("u_center", center)

	node.blur1c:setVec2("u_center", center)
	node.blur2c:setVec2("u_center", center)
	node.blur3c:setVec2("u_center", center)
	node.blur4c:setVec2("u_center", center)

	local s = math.min(w, h) / 960
    local dx = s / w
    local dy = s / h

    node.blur1t:setFloat("u_step_x", dx)
    node.blur1t:setFloat("u_step_y", dy)
    node.blur2t:setFloat("u_step_x", dx)
    node.blur2t:setFloat("u_step_y", dy)
    node.blur3t:setFloat("u_step_x", dx)
    node.blur3t:setFloat("u_step_y", dy)
    node.blur4t:setFloat("u_step_x", dx)
    node.blur4t:setFloat("u_step_y", dy)

	node.blur1x:setFloat("u_step_x", dx)
	node.blur1y:setFloat("u_step_y", dy)
	node.blur2x:setFloat("u_step_x", dx)
	node.blur2y:setFloat("u_step_y", dy)
	node.blur3x:setFloat("u_step_x", dx)
	node.blur3y:setFloat("u_step_y", dy)
	node.blur4x:setFloat("u_step_x", dx)
	node.blur4y:setFloat("u_step_y", dy)

	data.s = s
end

function Main:update (node, data, w, h, duration, elapsed, progress)
    local i = progress * FRAMES + 1
    local i0 = math.floor(i)
    local i1 = math.ceil(i)
    local t = i - i0

    local scale = Utils.mix(PROFILE.s[i0], PROFILE.s[i1], t) * SCALE0
    node.motion:setFloat("u_scale", scale)
    local angle = Utils.mix(PROFILE.r[i0], PROFILE.r[i1], t)
    node.motion:setFloat("u_angle", -angle)

    local x = Utils.mix(PROFILE.x[i0], PROFILE.x[i1], t)
    local y = Utils.mix(PROFILE.y[i0], PROFILE.y[i1], t)
    node.motion:setVec2("u_position", Amaz.Vector2f(x, y))

	local offset = OFFSET * Utils.step(330/FRAMES, 360/FRAMES, progress)
	node.morph:setFloat("u_intensity", offset)

    local Da = Utils.step(40/FRAMES, 0/FRAMES, progress)
    if self._enableNodes(node.blurD, Da > 0) then
        local Rd = RD * Da
        node.blur1t:setFloat("u_intensity", Rd)
        node.blur2t:setFloat("u_intensity", Rd * 0.5)
        node.blur3t:setFloat("u_intensity", Rd * 0.25)
        node.blur4t:setFloat("u_intensity", Rd * 0.125)
    end

	local Ra = Utils.step(330/FRAMES, 360/FRAMES, progress)
	if self._enableNodes(node.blurR, Ra > 0) then
        local Rr = RR * Ra * data.s
        node.blur1r:setFloat("u_step", Rr)
        node.blur2r:setFloat("u_step", Rr * 0.5)
		node.blur3r:setFloat("u_step", Rr * 0.25)
		node.blur4r:setFloat("u_step", Rr * 0.125)
	end

	local Ca = Utils.step(60/FRAMES, 160/FRAMES, progress) * Utils.step(270/FRAMES, 160/FRAMES, progress)
	if self._enableNodes(node.blurC, Ca > 0) then
		local Rc = RC * Ca
		node.blur1c:setFloat("u_radian", Rc)
		node.blur2c:setFloat("u_radian", Rc * 0.5)
		node.blur3c:setFloat("u_radian", Rc * 0.25)
		node.blur4c:setFloat("u_radian", Rc * 0.125)
	end

	local Qa0 = Utils.step(250/FRAMES, 40/FRAMES, progress)
	local Qa1 = Utils.step(360/FRAMES, 370/FRAMES, progress)
	if self._enableNodes(node.blurQ, Qa0 + Qa1 > 0) then
		local Rq = Qa0 > 0 and RQ0 * Qa0 or RQ1 * Qa1
		node.blur1x:setFloat("u_intensity", Rq)
		node.blur1y:setFloat("u_intensity", Rq)
		node.blur2x:setFloat("u_intensity", Rq * 0.5)
		node.blur2y:setFloat("u_intensity", Rq * 0.5)
		node.blur3x:setFloat("u_intensity", Rq * 0.25)
		node.blur3y:setFloat("u_intensity", Rq * 0.25)
		node.blur4x:setFloat("u_intensity", Rq * 0.125)
		node.blur4y:setFloat("u_intensity", Rq * 0.125)
	end
end

function Main._enableNodes (cameras, enabled)
    for _, camera in ipairs(cameras) do
        camera.visible = enabled
    end
	return enabled
end


return Main